
import {
  OrderStatus,
  PaymentMethod,
  PaymentStatus,
} from "../../generated/prisma/enums.js";
import { prisma } from "../../lib/prisma.js";
import { demoClockService } from "../demo-clock/demo-clock.service.js";
import { orderService } from "./order.service.js";

const INTERVAL_MS = 15_000;
const COD_CONFIRM_DELAY_MS = 15_000;
const TRANSITION_DELAY_MS = 72 * 60 * 60 * 1000;
const BATCH_SIZE = 100;

let timer: ReturnType<typeof setInterval> | null = null;
let isRunning = false;

export async function runOrderDeliveryScheduler() {
  if (isRunning) {
    return;
  }

  isRunning = true;

  try {
    // COD delay uses real elapsed time because Order.createdAt
    // is generated by the database, not by Demo Clock.
    const codCutoff = new Date(
      Date.now() - COD_CONFIRM_DELAY_MS,
    );

    const pendingCodOrders = await prisma.order.findMany({
      where: {
        status: OrderStatus.PENDING,
        paymentMethod: PaymentMethod.COD,
        paymentStatus: PaymentStatus.UNPAID,
        createdAt: { lte: codCutoff },
      },
      select: {
        id: true,
      },
      orderBy: { id: "asc" },
      take: BATCH_SIZE,
    });

    let codProcessed = 0;
    let codFailed = 0;

    for (const order of pendingCodOrders) {
      try {
        const processed =
          await orderService.autoProcessPendingCodOrderIfDue(
            order.id,
            codCutoff,
          );

        if (processed) {
          codProcessed += 1;
        }
      } catch (error) {
        codFailed += 1;

        console.error(
          "[OrderDeliveryScheduler] Failed to auto-process COD order:",
          order.id.toString(),
          error,
        );
      }
    }

    // Keep the existing Demo Clock-based 72-hour transitions.
    const now = await demoClockService.getNow();
    const cutoff = new Date(
      now.getTime() - TRANSITION_DELAY_MS,
    );

    const eligibleOrders = await prisma.order.findMany({
      where: {
        OR: [
          {
            status: OrderStatus.PROCESSING,
            processingAt: { not: null, lte: cutoff },
          },
          {
            status: OrderStatus.SHIPPING,
            shippingAt: { not: null, lte: cutoff },
          },
        ],
      },
      select: {
        id: true,
        status: true,
      },
      orderBy: { id: "asc" },
      take: BATCH_SIZE,
    });

    let transitioned = 0;
    let failed = 0;

    for (const order of eligibleOrders) {
      const nextStatus =
        order.status === OrderStatus.PROCESSING
          ? OrderStatus.SHIPPING
          : OrderStatus.DELIVERED;

      try {
        await orderService.updateOrderStatus(
          order.id,
          nextStatus,
        );
        transitioned += 1;
      } catch (error) {
        failed += 1;

        console.error(
          "[OrderDeliveryScheduler] Failed to transition order:",
          order.id.toString(),
          order.status,
          "->",
          nextStatus,
          error,
        );
      }
    }

    if (
      codProcessed > 0 ||
      codFailed > 0 ||
      transitioned > 0 ||
      failed > 0
    ) {
      console.log("[OrderDeliveryScheduler] Processed:", {
        codEligible: pendingCodOrders.length,
        codProcessed,
        codFailed,
        deliveryEligible: eligibleOrders.length,
        transitioned,
        failed,
      });
    }
  } catch (error) {
    console.error(
      "[OrderDeliveryScheduler] Failed:",
      error,
    );
  } finally {
    isRunning = false;
  }
}

export function startOrderDeliveryScheduler() {
  if (timer) {
    return;
  }

  timer = setInterval(() => {
    void runOrderDeliveryScheduler();
  }, INTERVAL_MS);

  timer.unref();
  void runOrderDeliveryScheduler();

  console.log("[OrderDeliveryScheduler] Started");
}

export function stopOrderDeliveryScheduler() {
  if (!timer) {
    return;
  }

  clearInterval(timer);
  timer = null;

  console.log("[OrderDeliveryScheduler] Stopped");
}
